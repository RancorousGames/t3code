"""Launch Monku no Mori from this checkout with its own pinnable Windows executable.

The generated .electron-runtime/mori-windows/Monku no Mori.exe carries Mori's icon
and embeds a small stub pointing at apps/mori-desktop/main.cjs. It uses the same
independent %APPDATA%/MonkuNoMori profile as the previous Electron launcher.
Pass --build to rebuild the renderer before launching.
"""

import argparse
import ctypes
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

from compile_t3 import embed_icon


RUNTIME_RELATIVE = Path(".electron-runtime") / "mori-windows"
CUSTOM_EXE_NAME = "Monku no Mori.exe"


def build_renderer(root: Path) -> None:
    web = root / "apps" / "mori-web"
    vp = root / "node_modules" / ".bin" / "vp.CMD"
    result = subprocess.run([str(vp), "build"], cwd=web, capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(f"Building apps/mori-web failed:\n\n{result.stdout}\n{result.stderr}")


def prepare_runtime(root: Path) -> Path:
    """Create a self-launching Electron runtime with a distinct executable and icon."""
    source = root / "apps" / "mori-desktop" / "node_modules" / "electron" / "dist"
    icon = root / "apps" / "mori-desktop" / "assets" / "monku.ico"
    source_exe = source / "electron.exe"
    for path in (source_exe, icon):
        if not path.is_file():
            raise RuntimeError(f"Missing {path}. Install Mori desktop dependencies first.")

    runtime = root / RUNTIME_RELATIVE
    custom_exe = runtime / CUSTOM_EXE_NAME
    marker_path = runtime / "source-runtime.json"
    marker = {
        "source": str(source),
        "electron_size": source_exe.stat().st_size,
        "electron_mtime_ns": source_exe.stat().st_mtime_ns,
        "icon_size": icon.stat().st_size,
        "icon_mtime_ns": icon.stat().st_mtime_ns,
    }
    try:
        existing_marker = json.loads(marker_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        existing_marker = None

    if existing_marker != marker or not custom_exe.is_file():
        try:
            if runtime.exists():
                shutil.rmtree(runtime)
            shutil.copytree(source, runtime)
            shutil.copy2(runtime / "electron.exe", custom_exe)
            embed_icon(custom_exe, icon)
            marker_path.write_text(json.dumps(marker, indent=2) + "\n", encoding="utf-8")
        except PermissionError as error:
            raise RuntimeError("Close Monku no Mori before updating its Windows executable.") from error

    # Electron automatically loads resources/app when the exe is opened directly
    # (including when the user pins it to the taskbar).
    app_dir = runtime / "resources" / "app"
    app_dir.mkdir(parents=True, exist_ok=True)
    (app_dir / "package.json").write_text(json.dumps({
        "name": "monku-no-mori-local",
        "private": True,
        "version": "0.5.0",
        "main": "index.cjs",
    }, indent=2) + "\n", encoding="utf-8")
    (app_dir / "index.cjs").write_text(
        '// Generated by launch_mori.py. Boot the current Mori source checkout.\n'
        'const path = require("node:path");\n'
        f'const root = {json.dumps(str(root))};\n'
        'const desktop = path.join(root, "apps", "mori-desktop");\n'
        'process.env.MORI_SOURCE_CHECKOUT = "1";\n'
        'delete process.env.ELECTRON_RUN_AS_NODE;\n'
        'process.chdir(desktop);\n'
        'require(path.join(desktop, "main.cjs"));\n',
        encoding="utf-8",
    )
    return custom_exe


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build", action="store_true", help="rebuild apps/mori-web/dist before launching")
    args = parser.parse_args()

    root = Path(__file__).resolve().parent
    desktop = root / "apps" / "mori-desktop"
    renderer = root / "apps" / "mori-web" / "dist" / "index.html"
    if args.build:
        build_renderer(root)
    if not renderer.is_file():
        raise RuntimeError("Missing Mori renderer. Run launch_mori.py --build first.")
    if not (desktop / "main.cjs").is_file():
        raise RuntimeError("Missing apps/mori-desktop/main.cjs.")

    exe = prepare_runtime(root)
    env = os.environ.copy()
    env.pop("ELECTRON_RUN_AS_NODE", None)
    subprocess.Popen(
        [str(exe)],
        cwd=exe.parent,
        env=env,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        creationflags=subprocess.DETACHED_PROCESS | subprocess.CREATE_NEW_PROCESS_GROUP,
    )


if __name__ == "__main__":
    try:
        main()
    except (OSError, RuntimeError) as error:
        message = f"Could not start Monku no Mori:\n\n{error}"
        ctypes.windll.user32.MessageBoxW(0, message, "Monku no Mori", 0x10)
        print(message, file=sys.stderr)
        sys.exit(1)
