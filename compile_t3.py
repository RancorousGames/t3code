"""Compile the T3 Code checkout and prepare its pinnable Windows runtime."""

import ctypes
from ctypes import wintypes
import json
import os
from pathlib import Path
import shutil
import struct
import subprocess
import sys

from t3_build_freshness import source_fingerprint, remember_build


CREATE_NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)
CUSTOM_EXE_NAME = "T3 Code (Custom).exe"
RUNTIME_RELATIVE = Path(".electron-runtime") / "windows-custom"


def resolve_node(root: Path, pnpm: str) -> Path:
    result = subprocess.run(
        [pnpm, "dlx", "node@24.13.1", "-p", "process.execPath"],
        cwd=root,
        capture_output=True,
        text=True,
        check=True,
        creationflags=CREATE_NO_WINDOW,
    )
    node = Path(result.stdout.strip().splitlines()[-1])
    if not node.is_file():
        raise RuntimeError("Could not locate Node 24.13.1.")
    return node


def electron_binary(root: Path, node: Path) -> Path:
    result = subprocess.run(
        [str(node), "-p", "require('electron')"],
        cwd=root / "apps" / "desktop",
        capture_output=True,
        text=True,
        check=True,
        creationflags=CREATE_NO_WINDOW,
    )
    binary = Path(result.stdout.strip().splitlines()[-1])
    if not binary.is_file():
        raise RuntimeError(f"Could not locate Electron runtime: {binary}")
    return binary


def custom_app_running(root: Path) -> bool:
    runtime = str((root / RUNTIME_RELATIVE / CUSTOM_EXE_NAME).resolve()).lower()
    script = (
        "Get-CimInstance Win32_Process | "
        "Where-Object { $_.Name -eq 'T3 Code (Custom).exe' } | "
        "Select-Object -ExpandProperty ExecutablePath"
    )
    result = subprocess.run(
        ["powershell.exe", "-NoProfile", "-NonInteractive", "-Command", script],
        capture_output=True,
        text=True,
        creationflags=CREATE_NO_WINDOW,
    )
    return runtime in result.stdout.lower()


def copy_runtime(source_exe: Path, runtime_dir: Path, icon_path: Path) -> Path:
    source_dir = source_exe.parent
    metadata_path = runtime_dir / "source-runtime.json"
    source_marker = {
        "source": str(source_dir),
        "electron_exe_size": source_exe.stat().st_size,
        "electron_exe_mtime_ns": source_exe.stat().st_mtime_ns,
        "icon_mtime_ns": icon_path.stat().st_mtime_ns,
    }

    current = None
    try:
        current = json.loads(metadata_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        pass

    custom_exe = runtime_dir / CUSTOM_EXE_NAME
    if current != source_marker or not custom_exe.is_file():
        if runtime_dir.exists():
            shutil.rmtree(runtime_dir)
        shutil.copytree(source_dir, runtime_dir)
        shutil.copy2(runtime_dir / "electron.exe", custom_exe)
        embed_icon(custom_exe, icon_path)
        metadata_path.write_text(
            json.dumps(source_marker, indent=2) + "\n",
            encoding="utf-8",
        )

    return custom_exe


def write_app_stub(root: Path, runtime_dir: Path) -> None:
    """Electron loads resources/app before its default app, so the bare exe opens this checkout."""
    desktop_package = json.loads(
        (root / "apps" / "desktop" / "package.json").read_text(encoding="utf-8")
    )
    app_dir = runtime_dir / "resources" / "app"
    app_dir.mkdir(parents=True, exist_ok=True)
    (app_dir / "package.json").write_text(
        json.dumps(
            {
                "name": "t3code-custom",
                "version": desktop_package["version"],
                "private": True,
                "main": "index.cjs",
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    (app_dir / "index.cjs").write_text(
        f"""// Generated by compile_t3.py. Launches the T3 Code source checkout.
const path = require("node:path");

const root = {json.dumps(str(root))};
const desktopDir = path.join(root, "apps", "desktop");

process.env.T3CODE_SOURCE_CHECKOUT = "1";
process.env.T3CODE_HOME = path.join(root, ".t3");
process.env.T3CODE_DISABLE_AUTO_UPDATE = "1";
process.env.T3CODE_DESKTOP_APP_USER_MODEL_ID = "com.t3tools.t3code.custom";
delete process.env.ELECTRON_RUN_AS_NODE;
delete process.env.VITE_DEV_SERVER_URL;

process.chdir(desktopDir);
require(path.join(desktopDir, "dist-electron", "boot.cjs"));
""",
        encoding="utf-8",
    )


def _resource_id(value: int):
    return ctypes.c_void_p(value)


def embed_icon(exe_path: Path, ico_path: Path) -> None:
    data = ico_path.read_bytes()
    if len(data) < 6:
        raise RuntimeError(f"Invalid ICO file: {ico_path}")

    reserved, icon_type, count = struct.unpack_from("<HHH", data, 0)
    if reserved != 0 or icon_type != 1 or count < 1:
        raise RuntimeError(f"Invalid ICO header: {ico_path}")

    entries = []
    offset = 6
    for index in range(count):
        entry = struct.unpack_from("<BBBBHHII", data, offset + index * 16)
        width, height, colors, reserved_byte, planes, bits, size, image_offset = entry
        image = data[image_offset : image_offset + size]
        if len(image) != size:
            raise RuntimeError(f"Truncated ICO image: {ico_path}")
        entries.append((width, height, colors, reserved_byte, planes, bits, image))

    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    begin = kernel32.BeginUpdateResourceW
    begin.argtypes = [wintypes.LPCWSTR, wintypes.BOOL]
    begin.restype = wintypes.HANDLE
    update = kernel32.UpdateResourceW
    update.argtypes = [
        wintypes.HANDLE,
        ctypes.c_void_p,
        ctypes.c_void_p,
        wintypes.WORD,
        ctypes.c_void_p,
        wintypes.DWORD,
    ]
    update.restype = wintypes.BOOL
    end = kernel32.EndUpdateResourceW
    end.argtypes = [wintypes.HANDLE, wintypes.BOOL]
    end.restype = wintypes.BOOL

    handle = begin(str(exe_path), False)
    if not handle:
        raise ctypes.WinError(ctypes.get_last_error())

    discard = True
    try:
        group = bytearray(struct.pack("<HHH", 0, 1, len(entries)))
        buffers = []
        for resource_id, entry in enumerate(entries, start=1):
            width, height, colors, reserved_byte, planes, bits, image = entry
            image_buffer = ctypes.create_string_buffer(image)
            buffers.append(image_buffer)
            if not update(
                handle,
                _resource_id(3),
                _resource_id(resource_id),
                0,
                ctypes.cast(image_buffer, ctypes.c_void_p),
                len(image),
            ):
                raise ctypes.WinError(ctypes.get_last_error())

            group.extend(
                struct.pack(
                    "<BBBBHHIH",
                    width,
                    height,
                    colors,
                    reserved_byte,
                    planes,
                    bits,
                    len(image),
                    resource_id,
                )
            )

        group_buffer = ctypes.create_string_buffer(bytes(group))
        buffers.append(group_buffer)
        if not update(
            handle,
            _resource_id(14),
            _resource_id(1),
            0,
            ctypes.cast(group_buffer, ctypes.c_void_p),
            len(group),
        ):
            raise ctypes.WinError(ctypes.get_last_error())

        discard = False
    finally:
        if not end(handle, discard):
            raise ctypes.WinError(ctypes.get_last_error())


def main(*, artifacts_only: bool = False) -> None:
    if os.name != "nt":
        raise RuntimeError("This build helper is intended for Windows.")

    root = Path(__file__).resolve().parent
    if custom_app_running(root) and not artifacts_only:
        raise RuntimeError("Close T3 Code (Custom) before updating its executable.")

    pnpm = shutil.which("pnpm.cmd")
    if not pnpm:
        raise RuntimeError("pnpm is not installed or not on PATH.")

    node = resolve_node(root, pnpm)
    env = os.environ.copy()
    env["PATH"] = str(node.parent) + os.pathsep + env.get("PATH", "")
    env.pop("ELECTRON_RUN_AS_NODE", None)

    # Capture before compilation: changes racing the build must not be marked fresh.
    source_before_build = source_fingerprint(root)
    print("Building T3 Code checkout...", flush=True)
    # Invoke the workspace build runner directly: pnpm 11 may attempt an
    # unrelated monorepo reinstall (and fail on a mobile package patch) before
    # it runs build:desktop. Desktop builds do not need that reinstall.
    vp = root / "node_modules" / ".bin" / "vp.cmd"
    if not vp.is_file():
        raise RuntimeError("Vite+ build runner is missing; install dependencies first.")
    env["NODE_OPTIONS"] = "--experimental-strip-types"
    subprocess.run(
        [str(vp), "run", "--filter", "@t3tools/desktop", "--filter", "t3", "build"],
        cwd=root,
        env=env,
        check=True,
    )

    if artifacts_only:
        if source_fingerprint(root) == source_before_build:
            # The executable and stub do not change for ordinary source edits:
            # compile in parallel with the running app, then restart in seconds.
            remember_build(root, source_before_build)
            print("Precompiled source artifacts verified for fast restart.", flush=True)
        else:
            print("Source changed during build; retry staging before restart.", flush=True)
            raise RuntimeError("Source changed during precompilation.")
        return

    source_exe = electron_binary(root, node)
    runtime_dir = root / RUNTIME_RELATIVE
    icon_path = root / "assets" / "dev" / "blueprint-windows.ico"
    if not icon_path.is_file():
        raise RuntimeError(f"Development icon not found: {icon_path}")
    print("Preparing pinnable Windows runtime...")
    # Prepare the entire Electron runtime before touching the installed one.
    # The restart worker has already shut down the custom app, so a directory
    # swap is safe; rollback preserves the previous launchable executable.
    staged_dir = runtime_dir.with_name("windows-custom-next")
    previous_dir = runtime_dir.with_name("windows-custom-previous")
    if staged_dir.exists():
        shutil.rmtree(staged_dir)
    copy_runtime(source_exe, staged_dir, icon_path)
    write_app_stub(root, staged_dir)
    if previous_dir.exists():
        shutil.rmtree(previous_dir)
    if runtime_dir.exists():
        runtime_dir.rename(previous_dir)
    try:
        staged_dir.rename(runtime_dir)
    except OSError:
        if previous_dir.exists() and not runtime_dir.exists():
            previous_dir.rename(runtime_dir)
        raise
    custom_exe = runtime_dir / CUSTOM_EXE_NAME

    marker = root / ".t3" / "compiled-source-build.json"
    marker.parent.mkdir(exist_ok=True)
    marker.write_text(
        json.dumps(
            {
                "custom_exe": str(custom_exe),
                "desktop_main": str(root / "apps" / "desktop" / "dist-electron" / "boot.cjs"),
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )

    if source_fingerprint(root) == source_before_build:
        remember_build(root, source_before_build)
        print("Recorded source fingerprint for subsequent fast restarts.", flush=True)
    else:
        print("Source changed during compilation; next restart must rebuild.", flush=True)
    print()
    print(f"Compiled successfully: {custom_exe}")
    print("The restart worker will relaunch T3 Code automatically.")


if __name__ == "__main__":
    try:
        if sys.argv[1:] == ["--build-only"]:
            main()
        elif sys.argv[1:] == ["--artifacts-only"]:
            main(artifacts_only=True)
        elif len(sys.argv) == 1:
            # Never terminate the very T3 instance that is hosting this build
            # command: the coordinator detaches before closing the window.
            subprocess.run(
                [sys.executable, str(Path(__file__).with_name("compile_and_launch_t3.py"))],
                cwd=Path(__file__).resolve().parent,
                check=True,
            )
        else:
            raise RuntimeError("Usage: compile_t3.py [--build-only|--artifacts-only]")
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"Build failed: {error}", file=sys.stderr)
        sys.exit(1)
